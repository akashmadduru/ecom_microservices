"""Product create/update: slug auto-generation and explicit-slug/collision
behavior, the generated `search_document` column, legacy free-text field
round-tripping, the DRAFT-by-default status, and one documented bug found
while writing these tests (create_product 500s when `attributes` is
omitted)."""

import pytest
from product_service.models import Product
from product_service.repo import slugify
from sqlalchemy import select, text

pytestmark = pytest.mark.integration


async def test_create_product_autogenerates_slug_from_title(client, as_seller):
    as_seller("42")
    resp = await client.post("/products", json={"title": "Ant Esports GW180 Corsa!", "attributes": {}})
    assert resp.status_code == 201
    body = resp.json()
    assert body["slug"] == slugify("Ant Esports GW180 Corsa!")


